-- ===========================================================================
-- PatternHunter AI — Server-side (24/7) Auto-Pilot
--
-- The browser no longer runs the execution loop. Toggling Auto-Pilot writes
-- `user_profiles.auto_pilot_enabled`, and the `auto-trade-worker` edge function
-- (triggered by pg_cron every minute) evaluates the Confluence engine and
-- executes through the Binance API using the encrypted credential vault.
--
-- This migration is idempotent (safe to re-run).
-- ===========================================================================

-- ---------------------------------------------------------------------------
-- 1. Per-user Auto-Pilot switch + server execution config
-- ---------------------------------------------------------------------------

ALTER TABLE public.user_profiles
  ADD COLUMN IF NOT EXISTS auto_pilot_enabled boolean NOT NULL DEFAULT false;

ALTER TABLE public.user_profiles
  ADD COLUMN IF NOT EXISTS auto_pilot_config jsonb NOT NULL DEFAULT '{}'::jsonb;

COMMENT ON COLUMN public.user_profiles.auto_pilot_enabled IS
  'When true the auto-trade-worker evaluates this user every minute. Writable only through set_auto_pilot_enabled().';
COMMENT ON COLUMN public.user_profiles.auto_pilot_config IS
  'Server-side Auto-Pilot config: marketType, leverage, riskPercent, maxOpenTrades, tradeDirectionMode, timeframe, symbols, minScore.';

CREATE INDEX IF NOT EXISTS idx_user_profiles_auto_pilot_enabled
  ON public.user_profiles (auto_pilot_enabled)
  WHERE auto_pilot_enabled = true;

-- ---------------------------------------------------------------------------
-- 2. Owner-facing toggle (the client cannot UPDATE user_profiles directly)
-- ---------------------------------------------------------------------------

CREATE OR REPLACE FUNCTION public.set_auto_pilot_enabled(
  p_enabled boolean,
  p_config jsonb DEFAULT NULL
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  uid uuid := auth.uid();
  next_enabled boolean;
  next_config jsonb;
BEGIN
  IF uid IS NULL THEN
    RETURN jsonb_build_object('success', false, 'error', 'Authentication required.');
  END IF;

  -- The client may tune execution parameters but never the safety ceilings.
  IF p_config IS NOT NULL AND jsonb_typeof(p_config) <> 'object' THEN
    RETURN jsonb_build_object('success', false, 'error', 'Config must be a JSON object.');
  END IF;

  SELECT auto_pilot_enabled, auto_pilot_config
    INTO next_enabled, next_config
  FROM public.user_profiles
  WHERE id = uid;

  IF NOT FOUND THEN
    RETURN jsonb_build_object('success', false, 'error', 'Profile not found.');
  END IF;

  next_enabled := COALESCE(p_enabled, next_enabled);
  next_config := COALESCE(next_config, '{}'::jsonb) || COALESCE(p_config, '{}'::jsonb);

  UPDATE public.user_profiles
  SET auto_pilot_enabled = next_enabled,
      auto_pilot_config = next_config,
      updated_at = now()
  WHERE id = uid;

  RETURN jsonb_build_object(
    'success', true,
    'enabled', next_enabled,
    'config', next_config
  );
END;
$$;

COMMENT ON FUNCTION public.set_auto_pilot_enabled(boolean, jsonb) IS
  'Toggles server-side Auto-Pilot for the caller and merges execution config. SECURITY DEFINER because clients hold SELECT-only rights on user_profiles.';

REVOKE ALL ON FUNCTION public.set_auto_pilot_enabled(boolean, jsonb) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.set_auto_pilot_enabled(boolean, jsonb) TO authenticated, service_role;

-- ---------------------------------------------------------------------------
-- 3. Worker bookkeeping (never client-readable)
-- ---------------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS public.auto_pilot_runs (
  user_id uuid PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
  last_run_at timestamptz,
  last_symbol text,
  last_candle_ms bigint,
  last_score integer,
  last_error text,
  updated_at timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE public.auto_pilot_runs ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.auto_pilot_runs FROM anon, authenticated;
GRANT ALL ON public.auto_pilot_runs TO service_role;

COMMENT ON TABLE public.auto_pilot_runs IS
  'Per-user worker state: last candle evaluated and last error. service_role only.';

CREATE TABLE IF NOT EXISTS public.auto_pilot_events (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  level text NOT NULL DEFAULT 'info' CHECK (level IN ('info', 'success', 'warn', 'error')),
  message text NOT NULL,
  symbol text,
  details jsonb,
  created_at timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE public.auto_pilot_events ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.auto_pilot_events FROM anon, authenticated;
GRANT ALL ON public.auto_pilot_events TO service_role;
GRANT SELECT ON public.auto_pilot_events TO authenticated;

DROP POLICY IF EXISTS "select_own_auto_pilot_events" ON public.auto_pilot_events;
CREATE POLICY "select_own_auto_pilot_events" ON public.auto_pilot_events
  FOR SELECT TO authenticated
  USING (auth.uid() = user_id);

CREATE INDEX IF NOT EXISTS idx_auto_pilot_events_user_created
  ON public.auto_pilot_events (user_id, created_at DESC);

-- Keep the log bounded per user (the worker also trims, this is a backstop).
CREATE OR REPLACE FUNCTION public.trim_auto_pilot_events(p_keep integer DEFAULT 200)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
BEGIN
  DELETE FROM public.auto_pilot_events e
  WHERE e.id NOT IN (
    SELECT id FROM public.auto_pilot_events
    ORDER BY created_at DESC
    LIMIT GREATEST(p_keep, 1)
  );
END;
$$;

REVOKE ALL ON FUNCTION public.trim_auto_pilot_events(integer) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.trim_auto_pilot_events(integer) TO service_role;

